-- ============================================================================
-- ERP ZUZA - Esquema SQL para Supabase (Plan Gratuito)
-- Incluye: Login simple, Mantenedores (Productos con visibilidad, Clientes,
-- Pedidos) y Reserva atómica de Nº de Pedido (OC) para sesiones simultáneas.
-- ============================================================================

-- 1. Usuarios del sistema (Login rápido con PIN)
create table if not exists usuarios (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  pin text not null default '1234',
  rol text not null default 'Ventas', -- 'Admin', 'Ventas', 'Producción'
  activo boolean not null default true,
  created_at timestamptz default now()
);

-- 2. Razones Sociales / Clientes Corporativos
create table if not exists razones_sociales (
  id integer primary key,
  rut text,
  razon_social text not null,
  contacto_principal text,
  created_at timestamptz default now()
);

-- 3. Contactos / Solicitantes frecuentes
create table if not exists contactos (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  razon_social_id integer references razones_sociales(id) on delete set null,
  destino_habitual text,
  despacho_habitual numeric default 7000,
  created_at timestamptz default now()
);

-- 4. Catálogo de Productos y Servicios
create table if not exists productos (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  pxq numeric not null default 0,
  ume text not null default 'un',
  categoria text default 'Cóctel / Pastelería',
  activo boolean not null default true, -- Visible (true) / Invisible (false) al armar pedidos
  created_at timestamptz default now()
);

-- 5. Cabecera de Comandas (Pedidos / Agenda)
create table if not exists comandas (
  id bigint generated by default as identity primary key,
  numero_correlativo integer not null unique,
  oc text not null unique,
  fecha_pedido date not null default current_date,
  hora_pedido text,
  cliente_nombre text not null,
  razon_social_id integer references razones_sociales(id) on delete set null,
  tip_serv text,
  tipo_servicio text not null default 'Servicio',
  fecha_entrega date not null,
  fecha_elaboracion date,
  fecha_envasado date,
  hrs_entrega text not null,
  obs text,
  texto_fecha text,
  descriptor_servicio text,
  tipo_documento text default 'Factura',
  estado_produccion text not null default 'Agendado',
  emision_dte text not null default 'Pendiente',
  dte integer,
  estado_pago text not null default 'Pendiente',
  fecha_pago date,
  guia_despacho text,
  total_valor numeric not null default 0,
  total_redondeado numeric not null default 0,
  creado_por text,
  created_at timestamptz default now()
);

-- Asegurar columna creado_por si la tabla ya existía de antes
alter table comandas add column if not exists creado_por text;

-- 6. Detalle de Comandas (Ítems)
create table if not exists comanda_items (
  id bigint generated by default as identity primary key,
  comanda_id bigint not null references comandas(id) on delete cascade,
  linea integer not null default 1,
  txt text not null,
  pxq numeric not null default 0,
  ume text not null default 'un',
  qty numeric not null default 1,
  neto numeric not null default 0,
  peso numeric default 0,
  valor numeric not null default 0,
  redondeo numeric not null default 0,
  bulto text,
  created_at timestamptz default now()
);

-- 7. Reservas de Nº de Pedido (OC) para pedidos simultáneos
create table if not exists reservas_oc (
  numero_correlativo integer primary key,
  oc text not null unique,
  session_id text not null unique,
  usuario_nombre text not null,
  expires_at timestamptz not null default (now() + interval '30 minutes'),
  created_at timestamptz default now()
);

create index if not exists idx_comandas_fecha_entrega on comandas(fecha_entrega);
create index if not exists idx_comandas_correlativo on comandas(numero_correlativo desc);
create index if not exists idx_comandas_pago on comandas(estado_pago);

-- ============================================================================
-- FUNCIONES ATÓMICAS PARA RESERVA DE OC SIMULTÁNEA
-- ============================================================================
create or replace function reservar_siguiente_oc(p_session_id text, p_usuario text)
returns table(numero_correlativo integer, oc text)
language plpgsql
security definer
as $$
declare
  v_num integer;
  v_oc text;
  v_max_cmd integer;
  v_max_res integer;
begin
  -- 1. Limpiar reservas vencidas
  delete from reservas_oc where expires_at < now();

  -- 2. Si esta sesión ya tiene una reserva vigente, renovarla y devolverla
  select r.numero_correlativo, r.oc into v_num, v_oc
  from reservas_oc r
  where r.session_id = p_session_id;

  if found then
    update reservas_oc
    set expires_at = now() + interval '30 minutes',
        usuario_nombre = p_usuario
    where session_id = p_session_id;
    return query select v_num, v_oc;
    return;
  end if;

  -- 3. Bloqueo ligero para evitar colisiones simultáneas
  lock table reservas_oc in share row exclusive mode;

  select coalesce(max(c.numero_correlativo), 290) into v_max_cmd from comandas c;
  select coalesce(max(r.numero_correlativo), 290) into v_max_res from reservas_oc r;

  v_num := greatest(v_max_cmd, v_max_res, 290) + 1;
  v_oc := 'ZRA-' || v_num::text;

  insert into reservas_oc (numero_correlativo, oc, session_id, usuario_nombre, expires_at)
  values (v_num, v_oc, p_session_id, p_usuario, now() + interval '30 minutes');

  return query select v_num, v_oc;
end;
$$;

create or replace function liberar_reserva_oc(p_session_id text)
returns void
language plpgsql
security definer
as $$
begin
  delete from reservas_oc where session_id = p_session_id;
end;
$$;

-- ============================================================================
-- PERMISOS Y POLÍTICAS RLS
-- ============================================================================
grant usage on schema public to anon, authenticated;
grant all on table usuarios, razones_sociales, contactos, productos, comandas, comanda_items, reservas_oc to anon, authenticated;
grant all on all sequences in schema public to anon, authenticated;
grant execute on function reservar_siguiente_oc(text, text) to anon, authenticated;
grant execute on function liberar_reserva_oc(text) to anon, authenticated;

alter table usuarios enable row level security;
alter table razones_sociales enable row level security;
alter table contactos enable row level security;
alter table productos enable row level security;
alter table comandas enable row level security;
alter table comanda_items enable row level security;
alter table reservas_oc enable row level security;

drop policy if exists "Acceso total usuarios" on usuarios;
drop policy if exists "Acceso total razones_sociales" on razones_sociales;
drop policy if exists "Acceso total contactos" on contactos;
drop policy if exists "Acceso total productos" on productos;
drop policy if exists "Acceso total comandas" on comandas;
drop policy if exists "Acceso total comanda_items" on comanda_items;
drop policy if exists "Acceso total reservas_oc" on reservas_oc;

create policy "Acceso total usuarios" on usuarios for all to anon, authenticated using (true) with check (true);
create policy "Acceso total razones_sociales" on razones_sociales for all to anon, authenticated using (true) with check (true);
create policy "Acceso total contactos" on contactos for all to anon, authenticated using (true) with check (true);
create policy "Acceso total productos" on productos for all to anon, authenticated using (true) with check (true);
create policy "Acceso total comandas" on comandas for all to anon, authenticated using (true) with check (true);
create policy "Acceso total comanda_items" on comanda_items for all to anon, authenticated using (true) with check (true);
create policy "Acceso total reservas_oc" on reservas_oc for all to anon, authenticated using (true) with check (true);

