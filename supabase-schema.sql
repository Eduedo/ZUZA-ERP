-- ERP ZUZA - Esquema SQL para Supabase (Plan Gratuito)
-- Mantiene exactamente la lógica de comandas ZRA-XXX, DTE, IVA 19% y redondeo
-- ============================================================================

-- 1. Razones Sociales / Clientes Corporativos
create table if not exists razones_sociales (
  id integer primary key,
  rut text,
  razon_social text not null,
  contacto_principal text,
  created_at timestamptz default now()
);

-- 2. Contactos / Solicitantes frecuentes
create table if not exists contactos (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  razon_social_id integer references razones_sociales(id) on delete set null,
  destino_habitual text,
  despacho_habitual numeric default 7000,
  created_at timestamptz default now()
);

-- 3. Catálogo de Productos y Servicios
create table if not exists productos (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  pxq numeric not null default 0,         -- Precio unitario con IVA
  ume text not null default 'un',         -- 'un', 'punit', 'kg', 'g'
  categoria text default 'Cóctel / Pastelería',
  activo boolean default true,
  created_at timestamptz default now()
);

-- 4. Cabecera de Comandas (Pedidos / Agenda)
create table if not exists comandas (
  id bigint generated by default as identity primary key,
  numero_correlativo integer not null unique, -- Ej: 290 para ZRA-290
  oc text not null unique,                    -- Ej: 'ZRA-290'
  fecha_pedido date not null default current_date,
  hora_pedido text,
  cliente_nombre text not null,               -- Ej: 'Francisca González'
  razon_social_id integer references razones_sociales(id) on delete set null,
  tip_serv text,                              -- Ej: '>7hrs', '>72hrs', etc.
  tipo_servicio text not null default 'Servicio', -- 'Servicio' | 'Servicio urgente'
  fecha_entrega date not null,
  fecha_elaboracion date,
  fecha_envasado date,
  hrs_entrega text not null,                  -- Ej: 'ETA 15:00 HRS'
  obs text,                                   -- Lugar de entrega / observaciones
  texto_fecha text,                           -- Ej: 'miércoles 25 de noviembre'
  descriptor_servicio text,                   -- Generado automáticamente
  tipo_documento text default 'Factura',      -- 'Factura', 'Boleta', 'Factura Mensual'
  estado_produccion text not null default 'Agendado', -- 'Agendado', 'En Producción', 'Entregado', 'Anulado'
  emision_dte text not null default 'Pendiente',      -- 'Pendiente', 'Emitida'
  dte integer,                                -- Número DTE (ej: 167)
  estado_pago text not null default 'Pendiente',      -- 'Pendiente', 'Recibido', 'PAGO', 'No corresponde'
  fecha_pago date,
  guia_despacho text,
  total_valor numeric not null default 0,
  total_redondeado numeric not null default 0,
  created_at timestamptz default now()
);

-- 5. Detalle de Comandas (Ítems)
create table if not exists comanda_items (
  id bigint generated by default as identity primary key,
  comanda_id bigint not null references comandas(id) on delete cascade,
  linea integer not null default 1,
  txt text not null,                          -- Descripción producto
  pxq numeric not null default 0,             -- Precio unitario con IVA
  ume text not null default 'un',
  qty numeric not null default 1,
  neto numeric not null default 0,            -- pxq / 1.19
  peso numeric default 0,
  valor numeric not null default 0,           -- pxq * qty (o peso)
  redondeo numeric not null default 0,        -- Redondeo a la centena
  bulto text,
  created_at timestamptz default now()
);

-- Índices para consultas rápidas de agenda y correlativos
create index if not exists idx_comandas_fecha_entrega on comandas(fecha_entrega);
create index if not exists idx_comandas_correlativo on comandas(numero_correlativo desc);
create index if not exists idx_comandas_pago on comandas(estado_pago);

-- Habilitar Row Level Security (RLS) con acceso público controlado por Anon Key
-- (Para uso interno rápido; si luego activas Auth de Supabase puedes restringirlo a authenticated)
alter table razones_sociales enable row level security;
alter table contactos enable row level security;
alter table productos enable row level security;
alter table comandas enable row level security;
alter table comanda_items enable row level security;

create policy "Acceso total razones_sociales" on razones_sociales for all using (true) with check (true);
create policy "Acceso total contactos" on contactos for all using (true) with check (true);
create policy "Acceso total productos" on productos for all using (true) with check (true);
create policy "Acceso total comandas" on comandas for all using (true) with check (true);
create policy "Acceso total comanda_items" on comanda_items for all using (true) with check (true);

